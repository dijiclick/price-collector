/** Interest relative to the market's top brand that makes a brand major / popular. */
const MAJOR_SHARE = 0.3;
const POPULAR_SHARE = 0.12;
/** Fewer distinct people than this says nothing about a market yet. */
const MIN_PEOPLE_MAJOR = 5;
const MIN_PEOPLE_POPULAR = 3;

/** Hand-list floor for a brand's score (see BrandRank.score). */
const HAND_SCORE_MAJOR = 0.6;
const HAND_SCORE_POPULAR = 0.3;

export interface BrandRank {
  /** Turns per round: 3 major, 2 popular, 1 the rest. */
  weight: number;
  /**
   * 0–1, how wanted the brand is here: its people over the top brand's, or the
   * hand list's floor, whichever is higher. Orders brands of a tier inside a
   * round, so a shelf of ten opens on Zara and Mango rather than on whichever
   * major happens to mark down deepest.
   */
  score: number;
}

const cache = new Map<CountryCode, Map<string, BrandRank>>();

/** Every brand ranked above the default (weight 1, score 0) in this market. */
export function brandRanks(country: CountryCode): Map<string, BrandRank> {
  const hit = cache.get(country);
  if (hit) return hit;
  const serves = new Set(brandsFor(country));
  const out = new Map<string, BrandRank>();
  const lift = (slug: string, weight: number, score: number) => {
    if (!serves.has(slug)) return;
    const was = out.get(slug) ?? { weight: WEIGHT_DEFAULT, score: 0 };
    out.set(slug, { weight: Math.max(was.weight, weight), score: Math.max(was.score, score) });
  };
  for (const b of [...POPULAR_EVERYWHERE, ...(POPULAR_BY_COUNTRY[country] ?? [])]) lift(b, WEIGHT_POPULAR, HAND_SCORE_POPULAR);
  for (const b of [...MAJOR_EVERYWHERE, ...(MAJOR_BY_COUNTRY[country] ?? [])]) lift(b, WEIGHT_MAJOR, HAND_SCORE_MAJOR);
  const seen = BRAND_INTEREST[country] ?? {};
  const top = Math.max(0, ...Object.values(seen));
  for (const [slug, people] of Object.entries(seen)) {
    const share = top > 0 ? people / top : 0;
    // Too few people to say anything: the hand list stands for this market.
    if (people < MIN_PEOPLE_POPULAR) continue;
    const weight =
      people >= MIN_PEOPLE_MAJOR && share >= MAJOR_SHARE ? WEIGHT_MAJOR
      : share >= POPULAR_SHARE ? WEIGHT_POPULAR
      : WEIGHT_DEFAULT;
    lift(slug, weight, Math.round(share * 100) / 100);
  }
  cache.set(country, out);
  return out;
}

export const brandWeight = (country: CountryCode, slug: string): number =>
  brandRanks(country).get(slug)?.weight ?? WEIGHT_DEFAULT;

/** A stable 0–1 number per brand (FNV-1a), so which brand of a tier leads is fixed but not alphabetical. */
export function brandHash(slug: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < slug.length; i++) h = Math.imul(h ^ slug.charCodeAt(i), 0x01000193);
  return ((h >>> 0) % 1024) / 1024;
}

/**
 * Every brand of the market as four parallel arrays for SQL — `$slugs::text[]`,
 * `$weights::float8[]`, `$scores::float8[]`, `$hashes::float8[]` — joined per
 * row with {@link rankJoin}. Everything per brand is worked out here, once,
 * not per row in Postgres: computing it per row cost ~0.5 s on the Turkish feed.
 */
export function brandRankParams(country: CountryCode): [string[], number[], number[], number[]] {
  const m = brandRanks(country);
  const slugs = [...new Set([...brandsFor(country), ...m.keys()])];
  return [
    slugs,
    slugs.map((b) => m.get(b)?.weight ?? WEIGHT_DEFAULT),
    slugs.map((b) => m.get(b)?.score ?? 0),
    slugs.map(brandHash),
  ];
}

/**
 * Joins each row to its brand's rank, adding `br_weight`, `br_score` and
 * `br_hash`. A hash join against one row per brand; `p` is the position of the
 * first of brandRankParams' four arrays (the other three follow it).
 */
export const rankJoin = (p: number, col = "brand"): string =>
  `LEFT JOIN unnest($${p}::text[], $${p + 1}::float8[], $${p + 2}::float8[], $${p + 3}::float8[]) AS br(br_slug, br_weight, br_score, br_hash) ON br.br_slug = ${col}`;

/**
 * SQL for a brand's k-th turn in a weighted round (lower comes first), on rows
 * that went through {@link rankJoin}: `(k - phase) / weight`. A weight-3 brand
 * takes three turns for a weight-1 brand's one. `phase` (0–1) is where in the
 * round the brand starts: 40% how wanted it is here, 30% its best cut (deep
 * cuts still lead), 30% a stable per-brand hash (ties inside a tier break the
 * same way every time, not alphabetically). On best cut alone the same deepest
 * majors led every shelf, and Zara — 40–60% off against 85–90% elsewhere —
 * never made one.
 */
export const rankSql = (k: string, bestPct: string): string =>
  `((${k} - (0.4 * COALESCE(br_score, 0) + 0.003 * LEAST(${bestPct}, 99) + 0.3 * COALESCE(br_hash, 0.5))) / COALESCE(br_weight, ${WEIGHT_DEFAULT}))::float8`;

/**
 * A follow set or a pick of a handful of brands. Weights apply to the open
 * feed and to a follow set (which is most of the market's brands), not to a
 * hand-picked few (the Marka sheet, the assistant's ≤6): someone who chose "Zara, Suwen" in the Marka sheet asked to
 * see both, and gets them in equal turns as before.
 */
export const WEIGHTED_MIN_BRANDS = 10;
export const weighsBrands = (brands: string[] | null | undefined): boolean =>
  !brands || brands.length === 0 || brands.length >= WEIGHTED_MIN_BRANDS;
