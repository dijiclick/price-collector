/**
 * How big a share of a mixed feed each brand gets (owner 2026-10-22: "more
 * important brands should show more in deals").
 *
 * The feed and the shelves let brands take turns so one brand's 600 deep cuts
 * cannot fill the screen. Equal turns had the opposite fault: Zara got 2 of the
 * first 200 cards, the same as Suwen, and none of the 120 shelf cards — its
 * 40–60% cuts lost every round to small brands at 85%. A brand's weight is how
 * many turns it takes per round: a major brand shows ~3 cards for a small
 * brand's 1, and the small brands still all appear.
 *
 * Three tiers, from two sources:
 * - What people here actually do (lib/brand-interest.ts, regenerated by
 *   scripts/brand-interest.mjs): distinct people who viewed, opened, tracked or
 *   filtered by the brand. Relative to the market's most-wanted brand, so it
 *   means the same in Turkey's hundreds of users and a new market's handful.
 * - A hand list for a cold start: a market with no users yet still opens on
 *   Zara, H&M and Nike rather than on whoever marks down deepest.
 * The higher of the two wins; neither can demote a brand.
 */
export const WEIGHT_MAJOR = 3;
export const WEIGHT_POPULAR = 2;
export const WEIGHT_DEFAULT = 1;

